import assert from 'node:assert/strict'
import { mkdir, readFile } from 'node:fs/promises'
import path from 'node:path'
import { chromium, expect } from '@playwright/test'

const baseURL = process.env.SMOKE_BASE_URL ?? 'http://127.0.0.1:4173/cukupduit/'
const artifacts = path.resolve('.qa')
await mkdir(artifacts, { recursive: true })
const browser = await chromium.launch({ headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1080 }, reducedMotion: 'reduce', acceptDownloads: true })
const page = await context.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
const checks = []
const passed = message => { checks.push(message); console.log(`PASS ${message}`) }

try {
  const response = await page.goto(baseURL, { waitUntil: 'networkidle' })
  assert.equal(response.status(), 200)
  await expect(page.getByRole('heading', { name: 'When Will You Have Cukup Duit?', exact: true })).toBeVisible()
  await expect(page.getByRole('img', { name: /Projected nominal net worth/ })).toBeVisible()
  await expect(page.locator('.recharts-surface').first()).toBeVisible()
  const originalAge = await page.locator('.hero-age').textContent()
  await page.screenshot({ path: path.join(artifacts, 'desktop-overview.png'), fullPage: true })
  passed('Desktop overview, live retirement result, SVG charts, and styles render')

  await page.getByRole('button', { name: 'Calculate My Financial Freedom', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Your profile', exact: true })).toBeVisible()
  const monthlySavings = page.getByRole('spinbutton', { name: 'Monthly savings', exact: true })
  await monthlySavings.fill('10000')
  await monthlySavings.blur()
  await page.getByRole('button', { name: 'Advanced mode', exact: true }).click()
  await expect(monthlySavings).toHaveValue('10000')
  await page.getByRole('button', { name: 'Quick mode', exact: true }).click()
  await expect(monthlySavings).toHaveValue('10000')
  passed('Editable savings and Quick/Advanced modes preserve the current plan')

  await page.getByRole('spinbutton', { name: 'Your current age', exact: true }).fill('35')
  await page.getByRole('spinbutton', { name: 'Your current age', exact: true }).blur()
  await expect(page.getByRole('spinbutton', { name: 'Your current age', exact: true })).toHaveValue('35')
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Assets & savings', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Advanced mode', exact: true }).click()
  const originalAccounts = await page.getByRole('textbox', { name: 'Account name', exact: true }).count()
  await page.getByRole('button', { name: 'Add account', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Account name', exact: true })).toHaveCount(originalAccounts + 1)
  const addedName = await page.getByRole('textbox', { name: 'Account name', exact: true }).last().inputValue()
  await page.getByRole('button', { name: `Remove ${addedName}`, exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Account name', exact: true })).toHaveCount(originalAccounts)
  passed('Guided navigation and investment account creation/removal work')

  await page.locator('.planner-step').filter({ hasText: 'Family' }).click()
  await page.getByRole('button', { name: 'Add child', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Name or label', exact: true })).toHaveCount(1)
  await page.getByRole('combobox', { name: 'Planning for', exact: true }).selectOption('future')
  await expect(page.getByRole('spinbutton', { name: 'Planned birth year', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Add gift', exact: true }).click()
  await expect(page.getByRole('spinbutton', { name: "Gift in today's money", exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Remove Child 1', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Name or label', exact: true })).toHaveCount(0)
  await page.locator('.planner-step').filter({ hasText: 'Legacy' }).click()
  await page.getByRole('button', { name: 'See my CukupDuit age', exact: true }).click()
  await expect(page.locator('.hero-age')).toBeVisible()
  await expect(page.locator('.hero-age')).not.toHaveText(originalAge)
  passed('Future child, education/gift controls, legacy step, and recalculated retirement result work')

  await page.getByRole('button', { name: "Today's MYR", exact: true }).click()
  await expect(page.getByRole('img', { name: /Projected inflation-adjusted net worth/ })).toBeVisible()
  await page.getByRole('button', { name: 'Nominal', exact: true }).click()
  await expect(page.getByRole('img', { name: /Projected nominal net worth/ })).toBeVisible()
  await page.getByRole('button', { name: 'Scenarios', exact: true }).click()
  await expect(page.getByRole('img', { name: /Comparison of net worth/ })).toBeVisible()
  await expect(page.getByText('Conservative', { exact: true }).first()).toBeVisible()
  await expect(page.getByText('Optimistic', { exact: true }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Insights', exact: true }).click()
  await expect(page.getByRole('heading', { name: /How Can You Have Cukup Duit Earlier/i })).toBeVisible()
  passed('Nominal/real chart views, scenarios, and computed optimizer render')

  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export plan as JSON', exact: true }).click()
  const download = await downloadPromise
  const savedPlan = path.join(artifacts, 'smoke-plan.json')
  await download.saveAs(savedPlan)
  const parsedPlan = JSON.parse(await readFile(savedPlan, 'utf8'))
  assert.ok(parsedPlan.profile || parsedPlan.currentAge, 'Export contains a financial profile')
  await page.getByRole('button', { name: 'Reset plan', exact: true }).click()
  await page.getByRole('button', { name: 'Reset to example', exact: true }).click()
  await page.locator('input[type="file"]').setInputFiles(savedPlan)
  await page.getByRole('button', { name: 'My plan', exact: true }).click()
  await page.locator('.planner-step').filter({ hasText: 'Profile' }).click()
  await expect(page.getByRole('spinbutton', { name: 'Your current age', exact: true })).toHaveValue('35')
  assert.equal(await page.evaluate(() => localStorage.length), 0)
  assert.equal((await context.cookies()).length, 0)
  passed('Explicit JSON export/import round-trip restores inputs without automatic browser persistence')

  await page.getByRole('button', { name: 'Share summary', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('financial values')
  const imagePromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download image', exact: true }).click()
  const shareImage = await imagePromise
  const imagePath = path.join(artifacts, 'smoke-summary.png')
  await shareImage.saveAs(imagePath)
  const png = await readFile(imagePath)
  assert.equal(png.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])), true)
  assert.equal(png.readUInt32BE(16), 1200)
  assert.equal(png.readUInt32BE(20), 720)
  await page.locator('input[type="file"]').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{"currentAge":"invalid"}') })
  await expect(page.getByRole('status')).toContainText('Profile.currentAge must be a number')
  await expect(page.getByRole('spinbutton', { name: 'Your current age', exact: true })).toHaveValue('35')
  passed('Private sharing warning, local PNG download, and invalid JSON rejection work')

  await page.getByRole('button', { name: 'Overview', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('.toast')).toHaveCount(0, { timeout: 7000 })
  await expect(page.getByRole('heading', { name: 'When Will You Have Cukup Duit?', exact: true })).toBeVisible()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Mobile overview has no horizontal overflow')
  await page.screenshot({ path: path.join(artifacts, 'mobile-overview.png'), fullPage: true })
  await page.getByRole('button', { name: 'My plan', exact: true }).click()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Mobile planner has no horizontal overflow')
  await page.screenshot({ path: path.join(artifacts, 'mobile-planner.png'), fullPage: true })
  await page.keyboard.press('Tab')
  assert.equal(await page.evaluate(() => document.activeElement !== document.body), true)
  assert.equal(await page.locator('input[type="number"]:not([id]), select:not([id])').count(), 0)
  passed('390px mobile overview/planner fit the viewport and keyboard focus reaches labelled controls')

  await page.reload({ waitUntil: 'networkidle' })
  await page.getByRole('button', { name: 'My plan', exact: true }).click()
  await expect(page.getByRole('spinbutton', { name: 'Your current age', exact: true })).toHaveValue('30')
  assert.deepEqual(errors, [], 'No uncaught browser or console errors')
  passed('Refresh starts a clean session and browser reports no runtime errors')
  console.log(`Smoke test complete: ${checks.length} checks passed at ${baseURL}`)
} finally {
  await browser.close()
}
