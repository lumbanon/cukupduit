test('configures savings only in Assets and derives percentage savings without a second editable amount', async ({ page }, testInfo) => {
  await page.goto('./')
  await page.getByRole('button', { name: 'My plan', exact: true }).click()
  const income = page.getByRole('spinbutton', { name: 'Monthly take-home income', exact: true })
  await expect(income).toBeVisible()
  await expect(page.getByRole('combobox', { name: 'How do you save?', exact: true })).toHaveCount(0)
  await expect(page.getByRole('spinbutton', { name: 'Monthly savings', exact: true })).toHaveCount(0)
  await expect(page.getByRole('spinbutton', { name: 'Income saved each month', exact: true })).toHaveCount(0)
  await income.fill('8000')
  await income.blur()
  await page.getByRole('button', { name: 'Advanced mode', exact: true }).click()
  await expect(income).toHaveValue('8000')
  await expect(page.getByRole('spinbutton', { name: 'Annual savings growth', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Quick mode', exact: true }).click()
  await page.locator('.planner-step').filter({ hasText: 'Assets' }).click()

  const method = page.getByRole('combobox', { name: 'How do you save?', exact: true })
  const fixed = page.getByRole('spinbutton', { name: 'Monthly savings', exact: true })
  await expect(method).toHaveCount(1)
  await expect(fixed).toHaveCount(1)
  await fixed.fill('1600')
  await fixed.blur()
  await expect(page.getByText(/Equivalent to 20% of your monthly take-home income/)).toBeVisible()
  await method.selectOption('percentage')
  const percent = page.getByRole('spinbutton', { name: 'Income saved each month', exact: true })
  await percent.fill('25')
  await percent.blur()
  const summary = page.getByLabel('Calculated monthly savings', { exact: true })
  await expect(summary).toContainText('2,000.00')
  expect(await summary.evaluate(element => element.tagName)).toBe('OUTPUT')
  await expect(fixed).toHaveCount(0)
  await page.getByRole('button', { name: 'Advanced mode', exact: true }).click()
  await expect(method).toHaveValue('percentage')
  await expect(percent).toHaveValue('25')
  await expect(summary).toContainText('2,000.00')
  await expect(fixed).toHaveCount(0)
  await expect(page.getByRole('spinbutton', { name: 'Monthly contribution allocation', exact: true }).nth(1)).toHaveValue('1500')
  await page.getByRole('button', { name: 'Quick mode', exact: true }).click()
  await expect(percent).toHaveValue('25')
  await page.screenshot({ path: `.qa/savings-${testInfo.project.name}.png`, fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)

  await page.getByRole('button', { name: 'Overview', exact: true }).click()
  const previousAge = await page.locator('.hero-age').textContent()
  await page.getByRole('button', { name: 'My plan', exact: true }).click()
  await page.locator('.planner-step').filter({ hasText: 'Profile' }).click()
  await income.fill('10000')
  await income.blur()
  await page.locator('.planner-step').filter({ hasText: 'Assets' }).click()
  await expect(method).toHaveValue('percentage')
  await expect(percent).toHaveValue('25')
  await expect(summary).toContainText('2,500.00')

  const exportPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export plan as JSON', exact: true }).click()
  const download = await exportPromise
  const chunks: Buffer[] = []
  for await (const chunk of await download.createReadStream()) chunks.push(Buffer.from(chunk))
  const saved = JSON.parse(Buffer.concat(chunks).toString()).profile
  expect(saved.savingsMode).toBe('percentage')
  expect(saved.savingsPercent).toBe(0.25)
  expect(saved.monthlyIncome).toBe(10000)
  expect(saved.monthlySavings).toBe(1600) // Preserved fixed entry, never a cached percentage result.
  expect(saved.accounts.map((a: { monthlyContribution: number }) => a.monthlyContribution)).toEqual([500, 1500, 500])

  await page.getByRole('button', { name: 'Overview', exact: true }).click()
  await expect(page.locator('.hero-age')).not.toHaveText(previousAge ?? '')
  const percentageAge = await page.locator('.hero-age').textContent()
  await page.getByRole('button', { name: 'My plan', exact: true }).click()
  await method.selectOption('fixed')
  await expect(fixed).toHaveValue('1600')
  await expect(summary).toHaveCount(0)
  await fixed.fill('2500')
  await fixed.blur()
  await page.getByRole('button', { name: 'Overview', exact: true }).click()
  await expect(page.locator('.hero-age')).toHaveText(percentageAge ?? '')
})
