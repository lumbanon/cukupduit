test('exports/imports explicitly, generates a local share image, and rejects invalid input', async ({ page, context }) => {
  await page.goto('./')
  const imported = { ...structuredClone(defaultProfile), currentAge: 35, monthlySavings: 8000 }
  const fileInput = page.locator('input[type="file"]')
  await fileInput.setInputFiles({ name: 'saved-plan.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ version: 1, profile: imported })) })
  await expect(page.getByRole('status')).toContainText('Plan imported')
  const exportPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export plan as JSON', exact: true }).click()
  const download = await exportPromise
  expect(download.suggestedFilename()).toBe('cukupduit-plan.json')
  const stream = await download.createReadStream()
  const chunks: Buffer[] = []
  for await (const chunk of stream) chunks.push(Buffer.from(chunk))
  expect(JSON.parse(Buffer.concat(chunks).toString()).profile.currentAge).toBe(35)

  await page.getByRole('button', { name: 'Share summary', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('financial values')
  const imagePromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download image', exact: true }).click()
  const image = await imagePromise
  expect(image.suggestedFilename()).toBe('cukupduit-summary.png')
  const imageStream = await image.createReadStream()
  const imageChunks: Buffer[] = []
  for await (const chunk of imageStream) imageChunks.push(Buffer.from(chunk))
  const png = Buffer.concat(imageChunks)
  expect(png.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]))).toBe(true)
  expect(png.readUInt32BE(16)).toBe(1200)
  expect(png.readUInt32BE(20)).toBe(720)

  await fileInput.setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ ...imported, currentAge: 'invalid' })) })
  await expect(page.getByRole('status')).toContainText('Profile.currentAge must be a number')
  await page.getByRole('button', { name: 'My plan', exact: true }).click()
  await expect(page.getByRole('spinbutton', { name: 'Your current age', exact: true })).toHaveValue('35')
  expect(await page.evaluate(() => localStorage.length)).toBe(0)
  expect(await context.cookies()).toHaveLength(0)
  await page.getByRole('button', { name: 'Reset plan', exact: true }).click()
  await page.getByRole('button', { name: 'Reset to example', exact: true }).click()
  await expect(page.getByRole('spinbutton', { name: 'Your current age', exact: true })).toHaveValue('30')
  await fileInput.setInputFiles({ name: 'saved-plan.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(imported)) })
  await expect(page.getByRole('spinbutton', { name: 'Your current age', exact: true })).toHaveValue('35')
  await page.reload()
  await page.getByRole('button', { name: 'My plan', exact: true }).click()
  await expect(page.getByRole('spinbutton', { name: 'Your current age', exact: true })).toHaveValue('30')
})

